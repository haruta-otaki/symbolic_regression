import sys
import numpy as np

class Node:
    def __init__(self, value=None, left=None, right=None):
        self.value = value
        self.left = left
        self.right = right
        self.fitness = 0
        self.error = sys.float_info.max

    def is_terminal(self):
        return self.left is None and self.right is None

    def evaluate(self, X):
        if self.is_terminal():
            if self.value in X:
                return X[self.value]
            return np.full(len(next(iter(X.values()))), float(self.value))
        l = self.left.evaluate(X)
        r = self.right.evaluate(X)
        if self.value == "+": return l + r
        if self.value == "-": return l - r
        if self.value == "*": return l * r
        if self.value == "/":
            # safe to divide
            safe = np.abs(r) > 1e-6
            # fallback
            result = np.ones_like(l)
            # calculate for safe rows only
            result[safe] = l[safe] / r[safe]
            return result
        raise ValueError(f"Unknown operator: {self.value}")

#find depth
    def depth(self):
      if self.is_terminal():
        return 1
      return 1 + max(self.left.depth(), self.right.depth())

#size
    def size(self):
      if self.is_terminal():
        return 1
      return 1 + self.left.size() + self.right.size()
 

  #copy of tree
    def copy(self):
      if self.is_terminal():
        new_node = Node(self.value)
      else:
        new_node = Node(
            self.value,
            self.left.copy(),
            self.right.copy()
        )

      new_node.fitness = self.fitness
      new_node.error = self.error
      return new_node

# print tree (generated by Claude)
    def __str__(self):
        return "\n".join(line.rstrip() for line in self._render()[0])

    def _render(self):
        """Return (lines, width, center) where center is the column of this node's label."""
        label = str(self.value)
        if self.is_terminal():
            return [label], len(label), (len(label) - 1) // 2

        l_lines, l_w, l_c = self.left._render()
        r_lines, r_w, r_c = self.right._render()

        # Space between the two subtrees; widen by one if needed so the
        # parent can sit exactly halfway between its children.
        gap = 3
        if (l_w + gap + r_c - l_c) % 2:
            gap += 1
        r_c += l_w + gap                  # right child's column in the combined block
        mid = (l_c + r_c) // 2            # parent's column
        k = (mid - l_c + 1) // 2          # how far the / and \ sit from the parent

        height = max(len(l_lines), len(r_lines))
        l_lines = l_lines + [" " * l_w] * (height - len(l_lines))
        r_lines = r_lines + [" " * r_w] * (height - len(r_lines))
        body = [a + " " * gap + b for a, b in zip(l_lines, r_lines)]
        width = l_w + gap + r_w

        # Centre the label on `mid`, growing the block if the label overhangs.
        start = mid - (len(label) - 1) // 2
        pad_l = max(0, -start)
        pad_r = max(0, start + len(label) - width)
        start, mid, width = start + pad_l, mid + pad_l, width + pad_l + pad_r
        body = [" " * pad_l + line + " " * pad_r for line in body]

        top = (" " * start + label).ljust(width)
        branches = (" " * (mid - k) + "/" + " " * (2 * k - 1) + "\\").ljust(width)
        return [top, branches] + body, width, mid


# Convert tree to mathematical expression

    def to_infix(self):
        if self.is_terminal():
            return str(self.value)

        return (
            f"({self.left.to_infix()} "
            f"{self.value} "
            f"{self.right.to_infix()})"
        )

# Get all nodes in a tree
def get_all_nodes(node, nodes):
    nodes.append(node)
        
    if not node.is_terminal():
        get_all_nodes(node.left, nodes)
        get_all_nodes(node.right, nodes)

    return nodes


# Get all non-terminal nodes
def get_all_inner_nodes(node, nodes):
    if node.is_terminal():
        return nodes

    nodes.append(node)

    get_all_inner_nodes(node.left, nodes)
    get_all_inner_nodes(node.right, nodes)

    return nodes


def generate_random_tree(operators, depth=5, p_terminal=0.2, p_x=0.5, variables=None, real_constants=False):

    if variables is None:
         variables = ["x"]
        
    if depth <= 1 or random.random() < p_terminal:
        if random.random() < p_x:
            return Node(random.choice(variables))
        if real_constants:
            constant = random.uniform(-10, 10) * (10 ** random.randint(-12, 0))
            return Node(str(constant))
        return Node(str(random.randint(-10, 10)))

    return Node(
        random.choice(operators),
        generate_random_tree(operators, depth - 1, p_terminal, p_x, variables, real_constants),
        generate_random_tree(operators, depth - 1, p_terminal, p_x, variables, real_constants))

def mutate(node, operators, p_x=0.5, variables=None, real_constants=False):

    if variables is None:
        variables = ["x"]

    #work on copy so original parent remains unchanged
    child = node.copy()
    
    # choose a random node to mutate
    nodes = get_all_nodes(child, [])
    mutate_node = random.choice(nodes)
    
    
    if random.random() < 0.5: 
        
        new_subtree = generate_random_tree(operators, depth=3, p_terminal=0.2, p_x=p_x, variables=variables, real_constants=real_constants)

        mutate_node.value = new_subtree.value
        mutate_node.left = new_subtree.left
        mutate_node.right = new_subtree.right

    else:

        
        if mutate_node.is_terminal():

            if random.random() < p_x:
                mutate_node.value = random.choice(variables)

            elif real_constants:
                constant = random.uniform(-10, 10) * (
                    10 ** random.randint(-12, 0)
                )
                mutate_node.value = str(constant)

            else:
                mutate_node.value = str(random.randint(-10, 10))

        else:
            mutate_node.value = random.choice(operators)

    child.fitness = 0
    return child
        

def crossover(parent1, parent2):

    #copy parents
    child = parent1.copy()
    donor = parent2.copy()
    
    # choose a random nodes to cross over
    donor_nodes = get_all_nodes(donor, [])
    donor_subtree = random.choice(donor_nodes).copy()

    child_nodes = get_all_nodes(child, [])
    target = random.choice(child_nodes)
    
    target.value = donor_subtree.value
    target.left = donor_subtree.left
    target.right = donor_subtree.right

    child.fitness = 0
    return child

